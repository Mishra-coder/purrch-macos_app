import AppKit
import SwiftUI
import CryptoKit

// MARK: - Model

struct ClipItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, url, files, image }

    var id = UUID()
    var kind: Kind
    var title: String
    /// Text or URL string.
    var text: String?
    /// File paths for `.files`.
    var paths: [String]?
    /// Saved PNG for `.image`.
    var imagePath: String?
    var size: Int64
    var sourceApp: String?
    var date: Date
    var pinned = false
    /// Used for de-duplication.
    var signature: String

    var tagLabel: String {
        switch kind {
        case .text: return "Text"
        case .url: return "Link"
        case .image: return "Image"
        case .files:
            guard let first = paths?.first else { return "File" }
            return FileMeta.label(URL(fileURLWithPath: first))
        }
    }

    var fileURLs: [URL] { (paths ?? []).map { URL(fileURLWithPath: $0) } }
    var imageURL: URL? { imagePath.map { URL(fileURLWithPath: $0) } }
}

// MARK: - Service

@MainActor
final class ClipboardService: ObservableObject {
    static let shared = ClipboardService()

    @Published private(set) var items: [ClipItem]
    @Published private(set) var lastCopiedID: UUID?

    static let imageDirectory: URL = {
        let dir = Store.directory.appendingPathComponent("clipboard-images", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir
    }()

    private let storeName = "clipboard"
    private let maxItems = 300
    private var changeCount: Int
    private var timer: Timer?

    /// Pasteboard markers used by password managers and apps that ask not to be recorded.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.agilebits.onepassword.secure",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
    ]

    private init() {
        items = Store.load("clipboard", default: [ClipItem]())
        changeCount = NSPasteboard.general.changeCount
    }

    /// Ordered for display: pinned first, then most recent.
    var ordered: [ClipItem] { items.filter(\.pinned) + items.filter { !$0.pinned } }

    func start() {
        guard timer == nil else { return }
        changeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardService.shared.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != changeCount else { return }
        changeCount = pb.changeCount
        capture(pb)
    }

    // MARK: Capture

    private func capture(_ pb: NSPasteboard) {
        let types = (pb.types ?? []).map(\.rawValue)
        guard !types.isEmpty, !types.contains(where: { Self.ignoredTypes.contains($0) }) else { return }
        let source = NSWorkspace.shared.frontmostApplication?.localizedName
        let now = Date()

        // Files
        if let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            let signature = "files:" + paths.joined(separator: "\n")
            if bump(signature, source: source) { return }
            let title = urls.count == 1 ? urls[0].lastPathComponent
                : "\(urls[0].lastPathComponent) +\(urls.count - 1) more"
            let size = urls.reduce(Int64(0)) { total, url in
                FileMeta.isDirectory(url) ? total : total + FileMeta.size(url)
            }
            insert(ClipItem(kind: .files, title: title, paths: paths, size: size,
                            sourceApp: source, date: now, signature: signature))
            return
        }

        // Images
        if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff) {
            let png: Data
            if pb.data(forType: .png) != nil {
                png = data
            } else if let rep = NSBitmapImageRep(data: data), let converted = rep.representation(using: .png, properties: [:]) {
                png = converted
            } else { return }
            let digest = SHA256.hash(data: png).prefix(12).map { String(format: "%02x", $0) }.joined()
            let signature = "image:" + digest
            if bump(signature, source: source) { return }
            let file = Self.imageDirectory.appendingPathComponent("\(digest).png")
            do { try png.write(to: file, options: .atomic) } catch { return }
            var title = "Image"
            if let rep = NSBitmapImageRep(data: png) { title = "Image \(rep.pixelsWide)×\(rep.pixelsHigh)" }
            insert(ClipItem(kind: .image, title: title, imagePath: file.path, size: Int64(png.count),
                            sourceApp: source, date: now, signature: signature))
            return
        }

        // Text / links
        guard let string = pb.string(forType: .string) ?? pb.string(forType: .URL) else { return }
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return }
        let signature = "text:" + string
        if bump(signature, source: source) { return }
        let isLink = !trimmed.contains(where: \.isWhitespace)
            && (URL(string: trimmed)?.scheme.map { ["http", "https"].contains($0.lowercased()) } ?? false)
        let firstLine = trimmed.split(whereSeparator: \.isNewline).first.map(String.init) ?? trimmed
        insert(ClipItem(kind: isLink ? .url : .text, title: String(firstLine.prefix(200)), text: string,
                        size: Int64(string.utf8.count), sourceApp: source, date: now, signature: signature))
    }

    /// Moves an identical existing item to the top. Returns true when found.
    private func bump(_ signature: String, source: String?) -> Bool {
        guard let index = items.firstIndex(where: { $0.signature == signature }) else { return false }
        var item = items.remove(at: index)
        item.date = Date()
        if let source { item.sourceApp = source }
        items.insert(item, at: 0)
        save()
        return true
    }

    private func insert(_ item: ClipItem) {
        items.insert(item, at: 0)
        while items.count > maxItems, let index = items.lastIndex(where: { !$0.pinned }) {
            deleteFiles(of: items.remove(at: index))
        }
        save()
    }

    private func deleteFiles(of item: ClipItem) {
        guard let path = item.imagePath else { return }
        // Only remove when no other item points at the same file.
        if !items.contains(where: { $0.imagePath == path }) {
            try? FileManager.default.removeItem(atPath: path)
        }
    }

    private func save() { Store.save(storeName, items) }

    // MARK: Actions

    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text:
            pb.setString(item.text ?? "", forType: .string)
        case .url:
            if let text = item.text, let url = URL(string: text.trimmingCharacters(in: .whitespacesAndNewlines)) {
                pb.writeObjects([url as NSURL])
            }
            pb.setString(item.text ?? "", forType: .string)
        case .files:
            pb.writeObjects(item.fileURLs as [NSURL])
        case .image:
            if let url = item.imageURL, let data = try? Data(contentsOf: url) {
                pb.setData(data, forType: .png)
                if let tiff = NSImage(data: data)?.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
            }
        }
        // Don't capture our own write as a new item.
        changeCount = pb.changeCount
        if let index = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: index)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
        lastCopiedID = item.id
        let id = item.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) {
            MainActor.assumeIsolated {
                if ClipboardService.shared.lastCopiedID == id { ClipboardService.shared.lastCopiedID = nil }
            }
        }
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].pinned.toggle()
        save()
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        deleteFiles(of: item)
        save()
    }

    func clearUnpinned() {
        let removed = items.filter { !$0.pinned }
        items.removeAll { !$0.pinned }
        removed.forEach(deleteFiles)
        save()
    }

    func dragProvider(for item: ClipItem) -> NSItemProvider {
        switch item.kind {
        case .text:
            return NSItemProvider(object: (item.text ?? "") as NSString)
        case .url:
            if let text = item.text, let url = URL(string: text.trimmingCharacters(in: .whitespacesAndNewlines)) {
                return NSItemProvider(object: url as NSURL)
            }
            return NSItemProvider(object: (item.text ?? "") as NSString)
        case .files:
            if let url = item.fileURLs.first, let provider = NSItemProvider(contentsOf: url) { return provider }
            return NSItemProvider()
        case .image:
            if let url = item.imageURL, let provider = NSItemProvider(contentsOf: url) { return provider }
            return NSItemProvider()
        }
    }
}

// MARK: - View

struct ClipboardModule: View {
    @ObservedObject private var service = ClipboardService.shared
    @Environment(\.theme) private var theme
    @State private var query = ""

    private var filtered: [ClipItem] {
        let all = service.ordered
        let q = query.trimmingCharacters(in: .whitespaces).lowercased()
        guard !q.isEmpty else { return all }
        return all.filter {
            $0.title.lowercased().contains(q)
                || ($0.text?.lowercased().contains(q) ?? false)
                || ($0.sourceApp?.lowercased().contains(q) ?? false)
                || $0.tagLabel.lowercased().contains(q)
                || ($0.paths?.contains { $0.lowercased().contains(q) } ?? false)
        }
    }

    var body: some View {
        VStack(spacing: 8) {
            HStack(spacing: 8) {
                SearchField(text: $query, placeholder: "Search clipboard")
                IconButton(systemName: "trash", size: 34, help: "Clear unpinned items") {
                    withAnimation(.easeOut(duration: 0.2)) { service.clearUnpinned() }
                }
            }
            let items = filtered
            if service.items.isEmpty {
                EmptyState(icon: "doc.on.clipboard", title: "Nothing copied yet",
                           subtitle: "Text, links, files and images you copy will appear here.")
            } else if items.isEmpty {
                EmptyState(icon: "magnifyingglass", title: "No matches", subtitle: "Try a different search.")
            } else {
                ScrollView(.vertical, showsIndicators: false) {
                    TimelineView(.periodic(from: .now, by: 30)) { _ in
                        LazyVStack(spacing: 6) {
                            ForEach(items) { item in
                                ClipRow(item: item, copied: service.lastCopiedID == item.id)
                            }
                        }
                    }
                }
            }
        }
    }
}

private struct ClipRow: View {
    let item: ClipItem
    let copied: Bool
    @Environment(\.theme) private var theme
    @State private var hovering = false

    var body: some View {
        ListRow {
            HStack(spacing: 10) {
                icon
                    .frame(width: 34, height: 34)
                    .background(RoundedRectangle(cornerRadius: 8, style: .continuous)
                        .fill(FileMeta.color(for: item.tagLabel).opacity(0.14)))
                    .clipShape(RoundedRectangle(cornerRadius: 8, style: .continuous))
                VStack(alignment: .leading, spacing: 3) {
                    Text(item.title)
                        .font(.system(size: 13, weight: .semibold))
                        .foregroundStyle(theme.text)
                        .lineLimit(1)
                        .truncationMode(.middle)
                    HStack(spacing: 5) {
                        Tag(text: item.tagLabel, color: FileMeta.color(for: item.tagLabel))
                        Text(meta)
                            .font(.system(size: 11))
                            .foregroundStyle(theme.secondaryText)
                            .lineLimit(1)
                    }
                }
                Spacer(minLength: 6)
                if copied {
                    Label("Copied", systemImage: "checkmark")
                        .font(.system(size: 11, weight: .semibold))
                        .foregroundStyle(theme.accent)
                        .transition(.opacity)
                }
                if hovering || item.pinned {
                    Button {
                        ClipboardService.shared.togglePin(item)
                    } label: {
                        Image(systemName: item.pinned ? "pin.fill" : "pin")
                            .font(.system(size: 12, weight: .semibold))
                            .foregroundStyle(item.pinned ? theme.accent : theme.secondaryText)
                            .frame(width: 24, height: 24)
                            .contentShape(Rectangle())
                    }
                    .buttonStyle(.plain)
                    .help(item.pinned ? "Unpin" : "Pin")
                }
            }
        }
        .contentShape(Rectangle())
        .onHover { hovering = $0 }
        .onTapGesture { ClipboardService.shared.copy(item) }
        .onDrag { ClipboardService.shared.dragProvider(for: item) }
        .contextMenu {
            Button("Copy") { ClipboardService.shared.copy(item) }
            Button(item.pinned ? "Unpin" : "Pin") { ClipboardService.shared.togglePin(item) }
            if item.kind == .files { Button("Reveal in Finder") { FileMeta.reveal(item.fileURLs) } }
            if item.kind == .url, let text = item.text, let url = URL(string: text.trimmingCharacters(in: .whitespacesAndNewlines)) {
                Button("Open Link") { NSWorkspace.shared.open(url) }
            }
            Divider()
            Button("Delete") { ClipboardService.shared.remove(item) }
        }
        .animation(.easeOut(duration: 0.15), value: copied)
    }

    private var meta: String {
        var parts: [String] = []
        if item.size > 0 { parts.append(Format.bytes(item.size)) }
        if let app = item.sourceApp { parts.append(app) }
        parts.append(Format.relative(item.date))
        return parts.joined(separator: " · ")
    }

    @ViewBuilder
    private var icon: some View {
        switch item.kind {
        case .text:
            Image(systemName: "text.alignleft")
                .font(.system(size: 14, weight: .semibold))
                .foregroundStyle(FileMeta.color(for: "text"))
        case .url:
            Image(systemName: "link")
                .font(.system(size: 14, weight: .semibold))
                .foregroundStyle(FileMeta.color(for: "link"))
        case .files:
            if let path = item.paths?.first {
                Image(nsImage: NSWorkspace.shared.icon(forFile: path))
                    .resizable().aspectRatio(contentMode: .fit).padding(3)
            }
        case .image:
            if let url = item.imageURL {
                FileThumbnailView(url: url, size: CGSize(width: 68, height: 68), contentMode: .fill)
            }
        }
    }
}
